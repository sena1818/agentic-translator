"""生成网站的公开任务类型。--check 用于 CI 防止契约漂移。"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.api.models.task_response import TaskResponse


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(repr(item) for item in schema["enum"])
    kind = schema.get("type")
    if kind == "object":
        return f"Record<string, {ts_type(schema.get('additionalProperties', {}))}>"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(
        kind, "unknown"
    )


def generate():
    schema = TaskResponse.model_json_schema()
    definitions = {**schema.get("$defs", {}), "TranslationTask": schema}
    parts = ["// Generated by scripts/generate_api_types.py; do not edit."]
    for name, definition in definitions.items():
        if "properties" not in definition:
            parts.append(f"export type {name} = {ts_type(definition)};")
        else:
            parts.append(f"export interface {name} {{")
            for field, prop in definition["properties"].items():
                parts.append(f"  {field}: {ts_type(prop)};")
            parts.append("}")
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "frontend/src/services/generated.ts"
    content = generate()
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("前端类型已过期，请执行 python scripts/generate_api_types.py")
    else:
        path.write_text(content)
